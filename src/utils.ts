/**
 * Utility functions for vite-plugin-shopify-critical.
 *
 * @packageDocumentation
 */

import path from "node:path";

import { CSS_EXTENSIONS, PLUGIN_NAME } from "./constants";
import type { CriticalFileMapping } from "./types";

/**
 * Checks if a source file is a CSS file.
 *
 * @param sourceFile - Source filename
 * @returns `true` if the file is a CSS file
 */
export function isCssFile(sourceFile: string): boolean {
  const ext = path.extname(sourceFile).toLowerCase();
  return CSS_EXTENSIONS.includes(ext);
}

/**
 * Generates the Liquid snippet content for development mode.
 * Uses dynamic URL construction like vite-plugin-shopify.
 *
 * @param devServerUrl - Vite dev server URL (e.g., "http://localhost:5173")
 * @param entrypointsDir - Path to entrypoints directory (e.g., "src/entrypoints")
 * @returns Liquid snippet content
 */
export function generateDevSnippetContent(
  devServerUrl: string,
  entrypointsDir: string
): string {
  const cssExtensionsList = CSS_EXTENSIONS.map((ext) => ext.slice(1)).join("|");

  return `{%- comment -%}
  IMPORTANT: This snippet is automatically generated by ${PLUGIN_NAME}.
  Do not attempt to modify this file directly, as any changes will be overwritten by the next build.
{%- endcomment -%}
{%- liquid
  assign file_url_prefix = '${devServerUrl}/${entrypointsDir}/'
  assign file_url = entry | prepend: file_url_prefix
  assign file_name = entry | split: '/' | last
  if file_name contains '.'
    assign file_extension = file_name | split: '.' | last
  endif
  assign css_extensions = '${cssExtensionsList}' | split: '|'
  assign is_css = false
  if css_extensions contains file_extension
    assign is_css = true
  endif
-%}
{%- if is_css -%}
<link rel="stylesheet" href="{{- file_url -}}" crossorigin="anonymous">
{%- else -%}
<script src="{{- file_url -}}" type="module"></script>
{%- endif -%}
`;
}

/**
 * Generates the Liquid snippet content for production mode.
 * Uses case/when structure with inline_asset_content.
 *
 * @param mappings - Array of file mappings (source to hashed output)
 * @returns Liquid snippet content
 */
export function generateProdSnippetContent(
  mappings: CriticalFileMapping[]
): string {
  if (mappings.length === 0) {
    return `{%- comment -%}
  IMPORTANT: This snippet is automatically generated by ${PLUGIN_NAME}.
  Do not attempt to modify this file directly, as any changes will be overwritten by the next build.
{%- endcomment -%}
{%- comment -%}No critical files found.{%- endcomment -%}
`;
  }

  const caseStatements = mappings
    .map(({ sourceFile, outputFile }) => {
      const isCss = isCssFile(sourceFile);
      if (isCss) {
        return `  {%- when '${sourceFile}' -%}\n    <style>{{- '${outputFile}' | inline_asset_content -}}</style>`;
      }
      return `  {%- when '${sourceFile}' -%}\n    <script>{{- '${outputFile}' | inline_asset_content -}}</script>`;
    })
    .join("\n");

  return `{%- comment -%}
  IMPORTANT: This snippet is automatically generated by ${PLUGIN_NAME}.
  Do not attempt to modify this file directly, as any changes will be overwritten by the next build.
{%- endcomment -%}
{%- case entry -%}
${caseStatements}
{%- endcase -%}
`;
}
